"""Check every TIFF in figures/output against the journal requirements and zip
them for upload, with a manifest.

    python figures/package_tiffs.py [out.zip]

Checks: RGB mode, LZW compression, resolution tag >= 300 dpi (>= 600 for the
combination art, >= 1200 for the line-art Figure 1), width within the column
limits, depth <= 9.167 in, TOC graphic <= 3.25 x 1.75 in.
"""
import os
import sys
import zipfile

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, os.pardir))
from succd import paths  # noqa: E402

# upload name -> (figure, source file, kind)
FILES = [
    ('TOC_graphic.tif', 'TOC graphic', 'toc'),
    ('fig1_workflow.tif', 'Figure 1', 'line'),
    ('fig2_geometries.tif', 'Figure 2', 'double'),
    ('fig3_circuit_cost.tif', 'Figure 3', 'double'),
    ('fig4_dE_matched_sets.tif', 'Figure 4', 'double'),
    ('fig5_residual_correlation.tif', 'Figure 5', 'double'),
    ('fig6_quadruple_correlation_energy.tif', 'Figure 6', 'double'),
    ('figA1_enhanced_cisd.tif', 'Figure A1', 'double'),
    ('figA2_sqd_deviation.tif', 'Figure A2', 'double'),
    ('figA3_determinant_counts.tif', 'Figure A3', 'double'),
    ('figA4_circuit_vs_sqd.tif', 'Figure A4', 'double'),
    ('figS1_validity_domain.tif', 'Figure S1', 'double'),
    ('figS2_predictors.tif', 'Figure S2', 'double'),
    ('figS3_parallelism.tif', 'Figure S3', 'double'),
    ('figS4_sqd_condition.tif', 'Figure S4', 'double'),
]
LIMITS = {'toc': (0.0, 3.25, 1.75, 600), 'line': (0.0, 3.33, 9.167, 1200),
          'single': (0.0, 3.33, 9.167, 600), 'double': (4.167, 7.0, 9.167, 600)}


def check(path, kind):
    im = Image.open(path)
    dpi = im.info.get('dpi', (0, 0))[0]
    w, h = im.size[0] / dpi, im.size[1] / dpi
    lo, hi, hmax, dpi_min = LIMITS[kind]
    problems = []
    if im.mode != 'RGB':
        problems.append('mode %s' % im.mode)
    if im.info.get('compression') != 'tiff_lzw':
        problems.append('compression %s' % im.info.get('compression'))
    if dpi < dpi_min - 0.5:
        problems.append('%d dpi < %d' % (dpi, dpi_min))
    if not (lo - 0.01 <= w <= hi + 0.01):
        problems.append('width %.2f in outside [%.2f, %.2f]' % (w, lo, hi))
    if h > hmax + 0.01:
        problems.append('height %.2f in > %.2f' % (h, hmax))
    return dict(px=im.size, dpi=round(dpi), w=w, h=h, mode=im.mode,
                bytes=os.path.getsize(path), problems=problems)


def main(out):
    rows, bad = [], 0
    for name, fig, kind in FILES:
        p = os.path.join(paths.FIGURES, name)
        if not os.path.exists(p):
            rows.append((name, fig, None)); bad += 1
            continue
        r = check(p, kind)
        rows.append((name, fig, r))
        bad += bool(r['problems'])
    lines = ['Figures for "A Selected Unitary Coupled Cluster Ansatz with Classically '
             'Determined Parameters" (J. Chem. Theory Comput.)',
             'TIFF, RGB, LZW; sizes at the journal print width.  Generated by '
             'figures/make_figures.py and figures/schematics.py of the companion repository.',
             '',
             '%-40s %-10s %-12s %5s %-9s %s' % ('file', 'figure', 'print size', 'dpi',
                                               'pixels', 'status')]
    for name, fig, r in rows:
        if r is None:
            lines.append('%-40s %-10s MISSING' % (name, fig))
            continue
        status = 'ok' if not r['problems'] else '; '.join(r['problems'])
        lines.append('%-40s %-10s %4.2f x %4.2f %5d %4dx%-4d %s'
                     % (name, fig, r['w'], r['h'], r['dpi'], r['px'][0], r['px'][1], status))
    manifest = '\n'.join(lines) + '\n'
    print(manifest)
    with zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED) as z:
        for name, fig, r in rows:
            if r is not None:
                z.write(os.path.join(paths.FIGURES, name), name)
        z.writestr('MANIFEST.txt', manifest)
    print('wrote', out, '(%d files, %d problem(s))' % (len(rows), bad))
    return bad


if __name__ == '__main__':
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else
                  os.path.join(paths.FIGURES, os.pardir, 'JCTC_figures_TIFF.zip')))
